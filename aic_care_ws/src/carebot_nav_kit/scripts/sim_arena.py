#       机器人半径 0.18 + 膨胀 0.22 = 0.40 m
#       行 52 那条 1.2m 口子两侧各被吃掉 → 只剩 0.4m
#       更关键的是：**行 51 与行 52 之间的墙在行 51 上产生致命区**，
