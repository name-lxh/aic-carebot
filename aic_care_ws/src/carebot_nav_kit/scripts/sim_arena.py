#      仿真的目的是让机器人走得开，不是复刻一间真房子。
#      口子开得刚刚好，只会让以后每次微调布局都要重算一遍。
_OPEN_FROM, _OPEN_TO = 1, 52


def build_grid():
    """把 ARENA 规范化成等宽的行，并开好起点开口。

    ⚠️ 必须逐行补齐宽度 —— 不等宽的地图会让射线投射和 PGM 写出都出错。
       `make_sim_map.py` 里也是这么处理的（`r.ljust(w, '#')`）。
    """
    grid = [list(r) for r in ARENA]
    w = max(len(r) for r in ARENA)
    for r in grid:
        while len(r) < w:
            r.append('#')
    # ★ 开起点开口：最后**两行**都开（见上面 _OPEN_FROM 的说明）
    for y in (len(grid) - 1, len(grid) - 2):
        row = grid[y]
        for x in range(_OPEN_FROM, min(_OPEN_TO, len(row))):
            row[x] = '.'
    return grid


