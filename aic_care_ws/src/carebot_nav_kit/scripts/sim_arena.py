def write_pgm(grid, path):
    """写出 PGM（P5 二进制灰度）。

    ROS 地图约定：
        白(254) = 可通行    黑(0) = 占据    205 = 未知

    ⚠️ 头部的注释用 **UTF-8** 编码，不能用 ascii ——
       PGM 规范里 `#` 开头的注释可以是任意字节，写中文没问题，
       但用 `.encode('ascii')` 会直接 UnicodeEncodeError。
       （第一版就是这么崩的。）
    """
    h = len(grid)
    w = len(grid[0])
    header = u'P5\n# AIC carebot 比赛场地仿真地图\n%d %d\n255\n' % (w, h)
    data = bytearray()
    for y in range(h):
        row = grid[y]
        for x in range(w):
            data.append(0 if row[x] == '#' else 254)
    with open(path, 'wb') as fp:
        fp.write(header.encode('utf-8'))
        fp.write(bytes(data))
    return w, h


def write_yaml(path, pgm_name, w, h):
    """写出地图 yaml。

    ⚠️ origin 必须是**地图左下角在世界坐标里的位置**。

        `fake_sensors.py` 的 `FakeWorld` 用**中心为原点**的世界坐标：

            ox = -w * res / 2        oy = -h * res / 2

        所以一个 40 格 @0.1m 的地图，世界范围是
        x ∈ [-2.0, +2.0]，y ∈ [-2.05, +2.05]，
        地图左下角就是 (-2.0, -2.05)。

        （`sim_map.yaml` 的 origin 是 [-4.2, -4.0]，也是同一个道理：
          40 格 @0.2m 的一半是 4.0。）

        ⚠️ 这个值写错的话，仿真里"看起来到了"但实车上偏一整个地图 ——
           因为 map 坐标系的原点对不上。
    """
    ox = -w * RESOLUTION / 2.0
    oy = -h * RESOLUTION / 2.0
    txt = (
        '# AIC carebot 比赛场地仿真地图\n'
        '# 由 carebot_nav_kit/scripts/sim_arena.py 生成\n'
        '#\n'
        '# ⚠️ 这是**仿真场地**，用于在虚拟机上验证比赛流程。\n'
        '#    实车的比赛场地地图要用 gmapping 现场建\n'
        '#    （见 docs/建图与导航操作手册.md）。\n'
        '#\n'
        '# 尺寸 %.1f m x %.1f m，分辨率 %.2f m/格\n'
        '# origin 是地图左下角在世界坐标里的位置 —— 与\n'
        '# fake_sensors.py 的 FakeWorld（中心为原点）对齐。\n'
        'image: %s\n'
        'resolution: %.2f\n'
        'origin: [%.3f, %.3f, 0.000]\n'
        'negate: 0\n'
        'occupied_thresh: 0.65\n'
        'free_thresh: 0.196\n'
    ) % (w * RESOLUTION, h * RESOLUTION, RESOLUTION,
         pgm_name, RESOLUTION, ox, oy)
    with io.open(path, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write(txt)
    return ox, oy


def preview(grid):
    """打印布局，并把点位标上去。

    ⚠️ 网格行号 0 是**最上面（+y 最大）**，而世界坐标 +y 向上 ——
       所以换算时是 `gy = h - 1 - int((wy - oy) / RES)`，
       漏掉这个翻转的话点位会上下颠倒。
    """
    h = len(grid)
    w = len(grid[0])
    ox = -w * RESOLUTION / 2.0
    oy = -h * RESOLUTION / 2.0
    show = [list(r) for r in grid]

    marks = {'B': 'room_B', 'C': 'room_C', 'D': 'room_D',
             'Q': 'qr_area', 'A': 'point_A', 'S': 'start'}
    for ch, name in sorted(marks.items()):
        wx, wy, _yaw = POINTS[name]
        gx = int((wx - ox) / RESOLUTION)
        gy = h - 1 - int((wy - oy) / RESOLUTION)
        if 0 <= gy < h and 0 <= gx < w:
            show[gy][gx] = ch

    print(u'')
    print(u'  场地 %.1f m × %.1f m，分辨率 %.2f m/格，网格 %d×%d'
          % (w * RESOLUTION, h * RESOLUTION, RESOLUTION, w, h))
    print(u'  世界坐标范围  x ∈ [%.2f, %.2f]   y ∈ [%.2f, %.2f]'
          % (ox, ox + w * RESOLUTION, oy, oy + h * RESOLUTION))
    print(u'')
    for i, r in enumerate(show):
        print(u'    %s' % u''.join(r))
    print(u'')
    print(u'  点位（世界坐标，米）：')
    for name in ('start', 'qr_area', 'point_A', 'room_B', 'room_C', 'room_D'):
        x, y, yaw = POINTS[name]
        print(u'    %-10s (%5.2f, %5.2f)  yaw=%.2f' % (name, x, y, yaw))
    return ox, oy


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true',
                    help=u'写出 pgm/yaml')
    ap.add_argument('--out', default=None,
                    help=u'输出目录（默认 carebot_nav_kit/maps）')
    ap.add_argument('--name', default='sim_arena',
                    help=u'地图文件名（不含扩展名）')
    args = ap.parse_args()

    grid = build_grid()
    h = len(grid)
    w = len(grid[0])
    ox, oy = preview(grid)

    # 可达性自检：点位必须落在可通行格上
    #
    # ⚠️ 光判"在不在墙里"还不够 —— 还要看**离墙多远**。
    #    实测踩过：点位都在可通行格里，但整张地图被膨胀层
    #    糊成一片高代价格，move_base 照样报 NO PATH（12 万条）。
    #
    #    判据：机器人半径 0.18 + 膨胀 0.22 = 需要 0.40m 间隙，
    #    这里按 0.45m 提醒（半格余量）。
    RADIUS = 0.18
    INFLATE = 0.22
    need = RADIUS + INFLATE + 0.05      # 0.45 m

    print(u'  点位可达性检查（含离墙间隙）：')
    bad = 0
    tight = 0
    for name in ('start', 'qr_area', 'point_A', 'room_B', 'room_C', 'room_D'):
        x, y, _yaw = POINTS[name]
        gx = int((x - ox) / RESOLUTION)
        gy = h - 1 - int((y - oy) / RESOLUTION)
        if not (0 <= gy < h and 0 <= gx < w):
            print(u'    ✘ %-10s 落在网格外' % name)
            bad += 1
            continue
        if grid[gy][gx] == '#':
            print(u'    ✘ %-10s 落在墙/障碍里（第 %d 行第 %d 列）'
                  % (name, gy, gx))
            bad += 1
            continue

        # 算最近的墙有多远。
        #
        # ⚠️ 扫描半径外的格子**不能当成"很远"** ——
        #    第一版把越界格按距离计入 dmin，于是空旷处的点算出 999 m，
        #    看着像"完全没问题"，实际上是把"没扫到"当成了"没墙"。
        #    正确做法：**越界就是墙**（地图边界外没有路），
        #    按边界距离算。
        r = int(need / RESOLUTION) + 2
        dmin = 999.0
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if dx == 0 and dy == 0:
                    continue
                yy, xx = gy + dy, gx + dx
                dist = ((dx * RESOLUTION) ** 2
                        + (dy * RESOLUTION) ** 2) ** 0.5
                if not (0 <= yy < h and 0 <= xx < w):
                    dmin = min(dmin, dist)          # 越界算墙
                elif grid[yy][xx] == '#':
                    dmin = min(dmin, dist)
        if dmin < need:
            print(u'    ⚠ %-10s 在可通行格，但离墙只有 %.2f m'
                  u'（建议 ≥%.2f m）—— 膨胀后会变成高代价，'
                  u'规划器可能绕不过去' % (name, dmin, need))
            tight += 1
        elif dmin >= 900:
            # 扫描半径内没找到墙 —— 说明很开阔。
            # ⚠️ 不要直接打印 999.00，那看起来像 bug；
            #    报"≥扫描半径"更诚实。
            print(u'    ✔ %-10s 在可通行格，离墙 ≥%.2f m（开阔）'
                  % (name, r * RESOLUTION))
        else:
            print(u'    ✔ %-10s 在可通行格，离墙 %.2f m' % (name, dmin))
    print(u'')
    if tight:
        print(u'  ⚠ 有 %d 个点位离墙偏近 —— 不一定失败，但优先挪开' % tight)
        print(u'')

    if bad:
        print(u'  ⚠️ 有 %d 个点位不可达 —— 先改 POINTS 再继续' % bad)
        return 1

    if not args.write:
        print(u'  （加 --write 才会写出文件）')
        return 0

    out = args.out
    if not out:
        here = os.path.dirname(os.path.abspath(__file__))
        out = os.path.join(os.path.dirname(here), 'maps')
    if not os.path.isdir(out):
        os.makedirs(out)

    pgm = os.path.join(out, args.name + '.pgm')
    yml = os.path.join(out, args.name + '.yaml')
    w, hh = write_pgm(grid, pgm)
    write_yaml(yml, args.name + '.pgm', w, hh)
    print(u'  已写出：')
    print(u'    %s  (%d×%d)' % (pgm, w, hh))
    print(u'    %s' % yml)
    print(u'')
    return 0


if __name__ == '__main__':
    sys.exit(main())
